# ── custom rings: a name + any time you choose (morning line-up, end of day, prayer…), not tied to periods ──
# app_settings central_custom = [{id, name, t: 'HH:MM', days: [0..6] (Monday = 0), tone, devices: null (all) | [ids], enabled}]
