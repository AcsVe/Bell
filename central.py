"""Central (office) bell — a school-wide bell played through the PA speakers by one office computer.

It is independent of the apps and of the section/teacher codes: the office player authenticates with its own
key, downloads this schedule plus the tones, and rings by itself — offline, even if the server is down.

Rings: the start of every period of every grade (classes get the group's *class* tone, breaks the group's
*break* tone). A "group" is one bell timing: a bell program (e.g. «الصفوف 7-10») or, for grades without an
assigned program that day, their stage's own times. Each group has its own two tones, so grades on different
timings hear different bells. Rings at the same minute with the same tone are played once.
"""
import hashlib
import json
import secrets
import uuid
from datetime import datetime, timedelta

from models import db, AppSetting, BellProgram, MediaFile, Stage
from services import resolve_grade_day, resolve_stage_day

