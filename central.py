CLASS_DEFAULTS = [k for k in CENTRAL_TONES if k.startswith('class-')]
BREAK_DEFAULTS = [k for k in CENTRAL_TONES if k.startswith('break-')]
SILENT = 'none'          # a group may switch one kind off (e.g. no break bell for the kindergarten)
ONLINE_SECONDS = 90      # the player polls every ~15 s


# ── settings ────────────────────────────────────────────────────────────────
def config():
    try:
        c = json.loads(AppSetting.get('central_bell') or '{}')
    except ValueError:
        c = {}
    c.setdefault('enabled', True)
    c.setdefault('volume', 100)
    c.setdefault('skip_dates', [])
    c.setdefault('tones', {})
    return c


def save_config(c):
    AppSetting.set('central_bell', json.dumps(c, ensure_ascii=False, sort_keys=True))


def tone_url(key):
    if key in CENTRAL_TONES:
        return f'/static/sounds/central/{key}.wav'
    if key and key.startswith('media:'):
        m = db.session.get(MediaFile, int(key.split(':', 1)[1])) if key.split(':', 1)[1].isdigit() else None
        return m.url if m else None
    return None


def tone_name(key, lang='ar'):
    if key == SILENT:
        return 'بلا رنين' if lang == 'ar' else 'No ring'
    if key in CENTRAL_TONES:
        return CENTRAL_TONES[key][0 if lang == 'ar' else 1]
    if key and key.startswith('media:') and key[6:].isdigit():
        m = db.session.get(MediaFile, int(key[6:]))
        return m.filename if m else '?'
    return '?'


def uploaded_tones():
    return MediaFile.query.filter_by(kind='central').order_by(MediaFile.id).all()


def all_tone_keys():
    return list(CENTRAL_TONES) + [f'media:{m.id}' for m in uploaded_tones()]


# ── groups ──────────────────────────────────────────────────────────────────
def _active_stages():
    return Stage.query.filter_by(active=True).order_by(Stage.sort_order, Stage.id).all()


def groups():
    """Every bell timing actually used by a grade on some school day, in a stable order (programs, then stages).
    [{key, ar, en, kind: program|stage, uses: [(weekday, grade name)...]}]"""
    found = {}
    for st in _active_stages():
        targets = [(g, g.name_ar, g.name_en or g.name_ar) for g in st.grades] or [(None, st.name_ar, st.name_en or st.name_ar)]
        for g, ar, _en in targets:
            for wd in st.weekday_list:
                prog = g.program_for(wd) if g is not None else None
                if prog is not None:
                    key = f'program:{prog.id}'
                    found.setdefault(key, {'key': key, 'kind': 'program', 'ar': prog.name, 'en': prog.name,
                                           'order': (0, prog.sort_order or 0, prog.id), 'uses': set()})
                else:
                    key = f'stage:{st.id}'
                    found.setdefault(key, {'key': key, 'kind': 'stage', 'ar': st.name_ar, 'en': st.name_en or st.name_ar,
                                           'order': (1, st.sort_order or 0, st.id), 'uses': set()})
                found[key]['uses'].add(ar)
    out = sorted(found.values(), key=lambda x: x['order'])
    for g in out:
        g['uses'] = sorted(g['uses'])
        del g['order']
    return out


def effective_tones(cfg=None, group_list=None):
    """{group key: {'class': key, 'break': key}} — saved choice, otherwise a different default per group."""
    cfg = cfg or config()
    group_list = group_list if group_list is not None else groups()
    valid = set(all_tone_keys()) | {SILENT}
    out = {}
    for i, g in enumerate(group_list):
        saved = cfg['tones'].get(g['key'], {})
        out[g['key']] = {
            'class': saved.get('class') if saved.get('class') in valid else CLASS_DEFAULTS[i % len(CLASS_DEFAULTS)],
            'break': saved.get('break') if saved.get('break') in valid else BREAK_DEFAULTS[i % len(BREAK_DEFAULTS)],
        }
    return out


def persist_defaults():
    """Freeze the defaults shown on the admin page, so adding a program later never shifts other groups' tones."""
    cfg = config()
    eff = effective_tones(cfg)
    if any(cfg['tones'].get(k) != v for k, v in eff.items()):
        cfg['tones'].update(eff)
        save_config(cfg)
        return True
    return False


# ── schedule ────────────────────────────────────────────────────────────────
def week_rings(cfg=None, only=None):
    """{weekday: [{'t': 'HH:MM', 'rings': [{'tone', 'kind', 'groups': [...], 'label'}]}]} for Monday=0..Sunday=6.
    only = a set of group keys (one bell device that serves some buildings/stages only); None = every group."""
    cfg = cfg or config()
    tones = effective_tones(cfg)
    days = {wd: {} for wd in range(7)}

    def add(wd, period, gkey, gname):
        if only is not None and gkey not in only:
            return
        tone = tones.get(gkey, {}).get('break' if period['kind'] == 'break' else 'class')
        if not tone or tone == SILENT:
            return
        slot = days[wd].setdefault(period['start'], {})
        r = slot.setdefault(tone, {'tone': tone, 'kind': period['kind'], 'groups': [], 'label': period['ar']})
        if gname not in r['groups']:
            r['groups'].append(gname)

    for st in _active_stages():
        for wd in st.weekday_list:
            if st.grades:
                for g in st.grades:
                    prog = g.program_for(wd)
                    gkey, gname = (f'program:{prog.id}', prog.name) if prog else (f'stage:{st.id}', st.name_ar)
                    for p in resolve_grade_day(g, wd):
                        add(wd, p, gkey, gname)
            else:
                for p in resolve_stage_day(st, wd):
                    add(wd, p, f'stage:{st.id}', st.name_ar)
    return {wd: [{'t': t, 'rings': list(slot.values())} for t, slot in sorted(slots.items())] for wd, slots in days.items()}


def player_payload(pid=None):
    """What one bell device plays: only its groups, at its volume (or the school volume)."""
    cfg = config()
    pl = players().get(pid) if pid else None
    only = set(pl['groups']) if pl and pl.get('groups') is not None else None
    week = week_rings(cfg, only)
    used = sorted({r['tone'] for day in week.values() for slot in day for r in slot['rings']})
    vol = pl.get('volume') if pl and pl.get('volume') else cfg.get('volume')
    body = {
        'enabled': bool(cfg['enabled']),
        'volume': max(0, min(100, int(vol or 100))),
        'skip_dates': sorted(set(cfg.get('skip_dates') or [])),
        'tz': 'Asia/Amman',
        'tones': {k: {'url': tone_url(k), 'name': tone_name(k)} for k in used if tone_url(k)},
        'days': {str(wd): v for wd, v in week.items()},
    }
    body['version'] = hashlib.sha1(json.dumps(body, sort_keys=True, ensure_ascii=False).encode()).hexdigest()[:16]
    return body


# ── bell devices (one per building / PA amplifier): key, groups, volume, status, test ring ──
# app_settings: central_players = {id: {name, key_hash, groups: null (= all) | [group keys], volume: null | 10-100}}
#               central_st:<id> = last status of that device;  central_test = {id, tone, url, at, target: 'all' | <id>}
def _h(key):
    return hashlib.sha256(('central:' + (key or '')).encode()).hexdigest()


def players():
    try:
        out = json.loads(AppSetting.get('central_players') or 'null')
    except ValueError:
        out = None
    if out is None:                       # before multiple devices: one office player with one key
        out = {}
        old = AppSetting.get('central_key_hash')
        if old:
            out['p1'] = {'name': 'جهاز المكتب', 'key_hash': old, 'groups': None, 'volume': None}
            try:
                st = AppSetting.get('central_player')
                if st and not AppSetting.get('central_st:p1'):
                    AppSetting.set('central_st:p1', st)
            except Exception:   # noqa: BLE001
                pass
            _save_players(out)
    return out


def _save_players(pls):
    AppSetting.set('central_players', json.dumps(pls, ensure_ascii=False, sort_keys=True))


def add_player(name):
    pls = players()
    n = 1
    while f'p{n}' in pls:
        n += 1
    pid = f'p{n}'
    key = secrets.token_urlsafe(24)
    pls[pid] = {'name': (name or '').strip()[:60] or f'جهاز {n}', 'key_hash': _h(key), 'groups': None, 'volume': None}
    _save_players(pls)
    return pid, key


def new_player_key(pid=None):
    """A new key for one device (the old key of THAT device stops). No device yet → creates «جهاز المكتب»."""
    pls = players()
    if not pls:
        return add_player('جهاز المكتب')[1]
    pid = pid if pid in pls else sorted(pls)[0]
    key = secrets.token_urlsafe(24)
    pls[pid]['key_hash'] = _h(key)
    _save_players(pls)
    return key


def update_player(pid, name=None, groups='keep', volume='keep'):
    pls = players()
    if pid not in pls:
        return False
    if name is not None and name.strip():
        pls[pid]['name'] = name.strip()[:60]
    if groups != 'keep':
        pls[pid]['groups'] = groups
    if volume != 'keep':
        pls[pid]['volume'] = volume
    _save_players(pls)
    return True


def delete_player(pid):
    pls = players()
    if pls.pop(pid, None) is not None:
        _save_players(pls)
        AppSetting.set(f'central_st:{pid}', '')


def check_key(key):
    """→ the device id this key belongs to, or None."""
    if not key:
        return None
    h = _h(key)
    for pid, pl in players().items():
        if pl.get('key_hash') and secrets.compare_digest(pl['key_hash'], h):
            return pid
    return None


def has_key():
    return bool(players())


def record_status(pid, data, ip):
    st = {k: data.get(k) for k in ('host', 'version', 'last_ring', 'next_ring', 'player', 'clock_drift', 'cached', 'error',
                                   'license', 'fingerprint', 'via')}
    st['seen'] = datetime.utcnow().strftime('%Y-%m-%dT%H:%M:%SZ')
    st['ip'] = ip
    AppSetting.set(f'central_st:{pid}', json.dumps(st, ensure_ascii=False))


def status(pid=None):
    """Status of one device; without an id: the first device (kept for the page header and old callers)."""
    if pid is None:
        pls = players()
        if not pls:
            return {}
        pid = sorted(pls)[0]
    try:
        st = json.loads(AppSetting.get(f'central_st:{pid}') or '{}')
    except ValueError:
        st = {}
    if st.get('seen'):
        age = (datetime.utcnow() - datetime.strptime(st['seen'], '%Y-%m-%dT%H:%M:%SZ')).total_seconds()
        st['age_s'] = int(age)
        st['online'] = age <= ONLINE_SECONDS
    return st


def devices():
    """[{id, name, groups, volume, st}] for the admin page, in creation order."""
    pls = players()
    return [dict(pl, id=pid, st=status(pid)) for pid, pl in sorted(pls.items(), key=lambda x: int(x[0][1:] or 0))]


def lan_urls():
    """This server's addresses on the school network (http://<ip>:<port>) — the office player falls back to them
    when the internet (and so 5.iajaward.org) is down, so it still gets changes and the server time."""
    import os
    import socket
    port = os.environ.get('PORT') or '8005'
    ips = set()
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(('10.255.255.255', 1))          # no packet is sent; picks the LAN interface
        ips.add(s.getsockname()[0])
        s.close()
    except OSError:
        pass
    try:
        ips.update(socket.gethostbyname_ex(socket.gethostname())[2])
    except OSError:
        pass
    good = sorted(ip for ip in ips if not ip.startswith(('127.', '169.254.', '0.')))
    return [f'http://{ip}:{port}' for ip in good][:4]


def request_test(tone, target='all'):
    t = {'id': uuid.uuid4().hex[:12], 'tone': tone, 'url': tone_url(tone), 'target': target or 'all',
         'at': datetime.utcnow().strftime('%Y-%m-%dT%H:%M:%SZ')}
    AppSetting.set('central_test', json.dumps(t))
    return t


def pending_test(pid=None):
    """A test ring asked for in the last 2 minutes for this device (or all); the player plays each id once."""
    try:
        t = json.loads(AppSetting.get('central_test') or 'null')
    except ValueError:
        return None
    if not t:
        return None
    if datetime.utcnow() - datetime.strptime(t['at'], '%Y-%m-%dT%H:%M:%SZ') > timedelta(minutes=2):
        return None
    target = t.get('target', 'all')
    if pid and target != 'all' and pid != target and pid not in (target if isinstance(target, list) else []):
        return None
    return t
